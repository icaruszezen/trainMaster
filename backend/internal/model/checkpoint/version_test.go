func moduleSet(names string) map[string]bool {
	set := map[string]bool{}
	for _, n := range strings.Fields(names) {
		set[n] = true
	}
	return set
}

func TestVersionFromArchitecture(t *testing.T) {
	for _, tt := range ultralyticsYAMLs {
		if got := versionFromArchitecture(moduleSet(tt.modules), tt.head, tt.end2end); got != tt.want {
			t.Errorf("%s: versionFromArchitecture = %q, want %q", tt.path, got, tt.want)
		}
	}

	// The yaml name and the architecture agree, except for these.
	disagree := map[string]bool{
		"26/yolo26-cls.yaml":           true, // the same architecture as yolo11-cls
		"11/yolo11-cls-resnet18.yaml":  true, // TorchVision backbone
		"v8/yolov8-cls-resnet50.yaml":  true, // ResNet backbone
		"v8/yolov8-cls-resnet101.yaml": true,
		"v8/yolov8-rtdetr.yaml":        true, // an RT-DETR head
	}
	for _, tt := range ultralyticsYAMLs {
		byName, _ := versionFromName(tt.path)
		if (byName == tt.want) == disagree[tt.path] {
			t.Errorf("%s: by name %q, by architecture %q", tt.path, byName, tt.want)
		}
	}

	// Custom models.
	for _, tt := range []struct {
		name, modules, head string
		end2end             bool
		want                string
	}{
		{"yolo11 trained end-to-end", "C2PSA C3k2 Concat Conv Detect SPPF Upsample", "Detect", true, version26},
		{"yolov8 trained end-to-end", "C2f Concat Conv Detect SPPF Upsample", "Detect", true, versionV8},
		{"yolov10 without the end2end flag", "C2f C2fCIB Concat Conv PSA SCDown SPPF Upsample v10Detect", "v10Detect", false, versionV10},
		{"C2f with a yolo26 head", "C2f Concat Conv SPPF Upsample Segment26", "Segment26", false, version26},
		{"A2C2f with an end-to-end head", "A2C2f C3k2 Concat Conv Detect Upsample", "Detect", true, version12},
		{"C2f with an unknown head", "C2f Concat Conv MyHead", "MyHead", false, ""},
		{"C2f without a head", "C2f Concat Conv", "", false, ""},
		{"nothing", "", "", false, ""},
		// Module classes of the layers (layerClasses), as in a model
		// without yaml.
		{"yolov8 layers", "C2f Concat Conv Detect SPPF Upsample", "Detect", false, versionV8},
	} {
		if got := versionFromArchitecture(moduleSet(tt.modules), tt.head, tt.end2end); got != tt.want {
			t.Errorf("%s: versionFromArchitecture = %q, want %q", tt.name, got, tt.want)
		}
	}
}

func TestValidScale(t *testing.T) {
	for s, want := range map[string]bool{
		"n": true, "s": true, "x": true, "b": true, "t": true, "p6": true, "nano": true,
		"": false, "N": false, "a-b": false, "n s": false, "abcdefghi": false, "长": false,
	} {
		if got := validScale(s); got != want {
			t.Errorf("validScale(%q) = %v", s, got)
		}
	}
}

