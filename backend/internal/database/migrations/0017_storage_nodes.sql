-- 0017_storage_nodes: storage nodes (存储节点) and online storage migrations.
--
-- Datasets (datasets/) and frozen data versions (exports/data-versions/) live
-- on a storage node: either the built-in local node (TM_DATA_DIR, id = 1), a
-- custom local directory, an S3-compatible object store (MinIO / RustFS /
-- Ceph / cloud S3), or an SMB/CIFS share (Windows / NAS). At most one storage
-- node is active (is_active = true) at any time and receives newly created
-- datasets and data versions; existing rows keep their storage_node_id so
-- switching the active node never breaks historical datasets or versions, and
-- storage_migrations moves items to the active node on demand.

CREATE TABLE storage_nodes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    kind            text NOT NULL CHECK (kind IN ('local', 's3', 'smb')),
    is_builtin      boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT false,
    config          jsonb NOT NULL DEFAULT '{}'::jsonb,
    credentials_enc bytea,
    last_checked_at timestamptz,
    last_status     text NOT NULL DEFAULT 'unknown' CHECK (last_status IN ('unknown', 'ok', 'error')),
    last_error      text NOT NULL DEFAULT '',
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (NOT is_builtin OR kind = 'local')
);

CREATE UNIQUE INDEX storage_nodes_name_key ON storage_nodes (lower(name));
CREATE UNIQUE INDEX storage_nodes_builtin_key ON storage_nodes (is_builtin) WHERE is_builtin;
CREATE UNIQUE INDEX storage_nodes_active_key ON storage_nodes (is_active) WHERE is_active;

-- Seed the undeletable built-in local storage node (id = 1) pointing dynamically
-- to TM_DATA_DIR at runtime, and advance the identity sequence past 1.
INSERT INTO storage_nodes (id, name, kind, is_builtin, is_active, config, last_status)
VALUES (1, '本机默认存储', 'local', true, true, '{}'::jsonb, 'ok');

SELECT setval(pg_get_serial_sequence('storage_nodes', 'id'), GREATEST((SELECT max(id) FROM storage_nodes), 1), true);

ALTER TABLE datasets
    ADD COLUMN storage_node_id bigint NOT NULL DEFAULT 1 REFERENCES storage_nodes (id) ON DELETE RESTRICT,
    ADD COLUMN recycled_in_place boolean NOT NULL DEFAULT false;

-- Folder names only have to be unique within the same storage node. On object
-- stores without fast directory rename (S3), recycled_in_place keeps the
-- prefix reserved until the 7-day purge deletes the objects.
DROP INDEX datasets_dir_name_key;
CREATE UNIQUE INDEX datasets_dir_name_key
    ON datasets (storage_node_id, lower(dir_name))
    WHERE deleted_at IS NULL OR NOT delete_files OR recycled_in_place;

CREATE INDEX datasets_storage_node_idx ON datasets (storage_node_id);

ALTER TABLE data_versions
    ADD COLUMN storage_node_id bigint NOT NULL DEFAULT 1 REFERENCES storage_nodes (id) ON DELETE RESTRICT;

CREATE INDEX data_versions_storage_node_idx ON data_versions (storage_node_id);

CREATE TABLE storage_migrations (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    target_type   text NOT NULL CHECK (target_type IN ('dataset', 'data_version')),
    target_id     bigint NOT NULL,
    target_name   text NOT NULL,
    from_node_id  bigint NOT NULL REFERENCES storage_nodes (id) ON DELETE CASCADE,
    to_node_id    bigint NOT NULL REFERENCES storage_nodes (id) ON DELETE CASCADE,
    delete_source boolean NOT NULL DEFAULT true,
    status        text NOT NULL CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'canceled')),
    files_done    integer NOT NULL DEFAULT 0,
    files_total   integer NOT NULL DEFAULT 0,
    bytes_done    bigint NOT NULL DEFAULT 0,
    bytes_total   bigint NOT NULL DEFAULT 0,
    error         text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    started_at    timestamptz,
    finished_at   timestamptz,
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX storage_migrations_active_idx
    ON storage_migrations (created_at, id)
    WHERE status IN ('queued', 'running');
CREATE INDEX storage_migrations_target_idx
    ON storage_migrations (target_type, target_id);
